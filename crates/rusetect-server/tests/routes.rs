/// (method, path as written in the router, is it under /api)
fn routes() -> Vec<(String, String, bool)> {
    let src = include_str!("../src/lib.rs");
    let start = src.find("let api = Router::new()").expect("api router");
    let api_end = start + src[start..].find(';').expect("end of api router");
    let pages_end = start + src[start..].find(".nest(\"/api\", api)").expect("nest");
    let mut out = vec![];
    for (block, api) in [(&src[start..api_end], true), (&src[api_end..pages_end], false)] {
        for line in block.lines().filter(|l| l.trim_start().starts_with(".route(\"")) {
            let path = line.split('"').nth(1).unwrap().to_string();
            for (m, needle) in [("GET", "get("), ("POST", "post(")] {
                if line.contains(needle) {
                    out.push((m.to_string(), path.clone(), api));
                }
            }
        }
    }
    out
}

fn table() -> String {
    let roles = ["viewer", "channel", "analyst", "supervisor"];
    let keys = Keys {
        keys: roles.iter().map(|r| (format!("key-{r}"), Analyst { analyst: r.to_string(), role: r.to_string() })).collect::<IndexMap<_, _>>(),
        demo_mode: false,
    };
    let checks: IndexMap<_, _> = HANDLER_CHECKS.into_iter().collect();
    let mut t = String::from("| Method | Route | No key | viewer | channel | analyst | supervisor | Further check in the handler |\n|---|---|---|---|---|---|---|---|\n");
    let rs = routes();
    for (method, path, api) in &rs {
        let full = if *api { format!("/api{}", if path == "/" { "" } else { path }) } else { path.clone() };
        let cell = |key: Option<&str>| -> String {
            if !api {
                return "open".into();
            }
            // a concrete value for each `{param}` segment
            let concrete: Vec<&str> = path.split('/').map(|s| if s.starts_with('{') { "X1" } else { s }).collect();
            match gate(&keys, method, &concrete.join("/"), key) {
                Ok(()) => "yes".into(),
                Err((code, _)) => code.to_string(),
            }
        };
        let row: Vec<String> = std::iter::once(cell(None)).chain(roles.iter().map(|r| cell(Some(&format!("key-{r}"))))).collect();
        let note = checks.get(format!("{method} {full}").as_str()).copied().unwrap_or(if *api { "" } else { "page or file, no key" });
        t += &format!("| {method} | `{full}` | {} | {note} |\n", row.join(" | "));
    }
    for k in checks.keys() {
        assert!(rs.iter().any(|(m, p, api)| format!("{m} {}", if *api { format!("/api{p}") } else { p.clone() }) == *k), "HANDLER_CHECKS names {k}, which is not a route");
    }
    t
}

#[test]
fn route_role_table_is_current() {
    let t = table();
    assert!(t.lines().count() > 60, "{t}");
    let doc_path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/SECURITY_REVIEW.md");
    let doc = std::fs::read_to_string(doc_path).expect("docs/SECURITY_REVIEW.md");
    let (a, b) = (doc.find(BEGIN).expect("begin marker") + BEGIN.len(), doc.find(END).expect("end marker"));
    let want = format!("\n{t}");
    if std::env::var("UPDATE_ROUTE_TABLE").as_deref() == Ok("1") {
        std::fs::write(doc_path, format!("{}{want}{}", &doc[..a], &doc[b..])).unwrap();
        return;
    }
    assert_eq!(&doc[a..b], want, "route table out of date: run UPDATE_ROUTE_TABLE=1 cargo test --release --test routes");
}
