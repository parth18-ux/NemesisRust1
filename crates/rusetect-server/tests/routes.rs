//! The route-to-role table in docs/SECURITY_REVIEW.md is generated from the code: every `.route(...)` in `build_app`
//! (src/lib.rs) is run through the access rule (`rusetect::security::gate`) once per role, outside demo mode. The test
//! fails when the table in the document differs; `UPDATE_ROUTE_TABLE=1 cargo test --test routes` rewrites it.

